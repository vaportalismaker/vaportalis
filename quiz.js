let currentCategory = "";
// Зберігаємо чергу перемішаних індексів для кожної категорії, щоб питання не повторювалися
let questionQueues = {};

// 1. Створюємо 7 кнопок категорій при завантаженні
function initCategories() {
    categoriesGrid.innerHTML = "";
    Object.keys(quizData).forEach(categoryName => {
        const btn = document.createElement("button");
        btn.className = "cat-btn";
        btn.textContent = categoryName;
        btn.addEventListener("click", () => startCategory(categoryName));
        categoriesGrid.appendChild(btn);
    });
}

// Перемішування масиву (алгоритм Фішера — Єйтса)
function shuffleArray(arr) {
    for (let i = arr.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [arr[i], arr[j]] = [arr[j], arr[i]];
    }
    return arr;
}

// Отримуємо наступне випадкове питання без повторів
function getNextQuestion(categoryName) {
    const questions = quizData[categoryName];
    if (!questionQueues[categoryName] || questionQueues[categoryName].length === 0) {
        const indices = questions.map((_, index) => index);
        questionQueues[categoryName] = shuffleArray(indices);
    }
    const nextIndex = questionQueues[categoryName].pop();
    return questions[nextIndex];
}

// 2. Запуск обраної категорії
function startCategory(categoryName) {
    currentCategory = categoryName;
    currentCategoryBadge.textContent = categoryName;
    categoryScreen.classList.add("hidden");
    quizScreen.classList.remove("hidden");
    loadQuestion();
}

// 3. Виведення запитання та варіантів
function loadQuestion() {
    const q = getNextQuestion(currentCategory);

    // Скидаємо попередній стан
    feedbackBox.classList.add("hidden");
    feedbackBox.classList.remove("is-correct", "is-wrong");
    nextControls.classList.add("hidden");
    optionsContainer.innerHTML = "";

    questionText.textContent = q.question;

    q.options.forEach((optionText, index) => {
        const btn = document.createElement("button");
        btn.className = "option-btn";
        btn.textContent = optionText;
        btn.addEventListener("click", () => handleAnswer(index, q));
        optionsContainer.appendChild(btn);
    });
}

// 4. Обробка відповіді гравця
function handleAnswer(selectedIndex, questionObj) {
    const allButtons = optionsContainer.querySelectorAll(".option-btn");
    const isCorrect = selectedIndex === questionObj.correct;

    // Блокуємо повторні кліки та підсвічуємо кнопки
    allButtons.forEach((btn, idx) => {
        btn.disabled = true;
        if (idx === questionObj.correct) {
            btn.classList.add("correct");
        } else if (idx === selectedIndex && !isCorrect) {
            btn.classList.add("wrong");
        }
    });

    // Показуємо статус та пояснення
    feedbackBox.classList.remove("hidden");
    if (isCorrect) {
        feedbackBox.classList.add("is-correct");
        feedbackStatus.textContent = "✔ Правильно!";
    } else {
        feedbackBox.classList.add("is-wrong");
        feedbackStatus.textContent = `✖ Неправильно! Правильна відповідь: «${questionObj.options[questionObj.correct]}»`;
    }

    feedbackExplanation.textContent = questionObj.explanation;
    nextControls.classList.remove("hidden");
}

// Повернення до вибору категорій
function showCategories() {
    quizScreen.classList.add("hidden");
    categoryScreen.classList.remove("hidden");
}

document.getElementById("back-to-cats-btn").addEventListener("click", showCategories);
document.getElementById("finish-turn-btn").addEventListener("click", showCategories);
document.getElementById("next-question-btn").addEventListener("click", loadQuestion);

